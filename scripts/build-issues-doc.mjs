#!/usr/bin/env node
/**
 * Renderer: docs/issues.json + its four registers → docs/issues.md.
 *
 * Markdown, for the same reason use-cases.md is markdown and the validation
 * guide is not: this is read on GitHub by someone deciding what to pick up
 * next, not on a phone in a masjid basement.
 *
 * Every title, and every deep link, is read out of the source document at build
 * time — nothing in this page is stored in issues.json. That is the point of
 * the catalog and it is worth being strict about: the moment a title lives in
 * two files, one of them is a copy that will be right for a while and then
 * quietly stop being right, and a stale index reads exactly like a fresh one.
 *
 * Two tables, deliberately. "Open" is the working list, worst first, and is
 * what someone reads to choose. "Closed" is the memory — it is the table that
 * makes `fixed` mean something, because every row in it names the test that
 * would fail if the thing came back, and a row that could not name one was
 * refused by the gate before it ever got here.
 *
 * The file is generated and committed, and gate-issues.mjs fails when the
 * committed copy was built from a different source. Do not hand-edit it.
 *
 * Usage:  node scripts/build-issues-doc.mjs
 */
import { writeFileSync } from "node:fs";
import { readLedger } from "./validation-ledger.mjs";
import { readIssues, linker, issuesHash, DOC_PATH, STATUS_ORDER, SECTION_HEADING } from "./issues.mjs";

const issues = readIssues();
const checks = readLedger().checks ?? [];
const ledgerById = new Map(checks.map((c) => [c.id, c]));

const statusOf = (i) =>
  i.source.ledger ? (ledgerById.get(i.source.ledger)?.status ?? "?") : i.status;

// Titles and hrefs are read out of the owning document — see `linker`, which
// docs/tasks.md shares so the two pages cannot link the same item differently.
const link = linker(ledgerById);

const cell = (s) => (s ?? "").replace(/\|/g, "\\|");

function row(i) {
  const [title, href] = link(i);
  const wait = (i.blockedBy ?? []).join(", ");
  return `| [${cell(title)}](${href}) | ${statusOf(i)} | ${i.severity} | ${i.owner} | ${cell(wait) || "—"} |`;
}

const closedRow = (i) => {
  const [title, href] = link(i);
  return `| [${cell(title)}](${href}) | ${statusOf(i)} | ${cell(i.closedBy ?? "—")} |`;
};

const isClosed = (i) => ["answered", "fixed", "done"].includes(statusOf(i));
const open = issues.filter((i) => !isClosed(i));
const closed = issues.filter(isClosed);

const order = STATUS_ORDER.concat(["pending", "done"]);
const bySeverityThenStatus = (a, b) =>
  order.indexOf(statusOf(a)) - order.indexOf(statusOf(b)) || a.id.localeCompare(b.id);

const out = [];
const w = (s = "") => out.push(s);

w("<!-- generated by scripts/build-issues-doc.mjs — do not edit; run `make issues-doc` -->");
w(`<!-- issues-hash: ${issuesHash(issues)} -->`);
w();
w("# Open items");
w();
w("Everything this repo has written down as unfinished, in one place, indexed from");
w("[`issues.json`](issues.json). Nothing here is authored: every title below is read out of the");
w("document that owns the item, and the link goes there. Change an item where it lives, then run");
w("`make issues-doc`.");
w();
w("The four registers, and why they stayed separate until now:");
w();
w("| register | holds |");
w("| --- | --- |");
w("| [`PLAN.md` §Open follow-ups](PLAN.md#open-follow-ups) | the roadmap of record; compound narratives, each keeping its own history |");
w("| [`backlog.md`](backlog.md) | performance and optimization, scheduled by evidence rather than by loop |");
w(`| the design docs' §${SECTION_HEADING} | what a document knows it has not settled |`);
w("| [`validation/ledger.json`](validation/ledger.json) | the checks a machine cannot run |");
w();
w("Each is internally disciplined; none could see the others. `pnpm gate:issues` now reads all four");
w("and fails when one of them has an item this index does not, which is the direction that matters —");
w("a defect nobody points at is invisible no matter how many pointers resolve.");
w();
w("**The words.** `confirmed` — reproduced, with numbers in its source. `suspected` — read from the");
w("code, never reproduced. `open` — undecided, nothing blocking. `blocked` — the next step is named");
w("and unavailable. `answered` — decided, nothing owed in code. `fixed` — closed in code *and* in a");
w("test that would fail if it came back; the gate refuses the word without one.");
w();
w(`## Open — ${open.length}`);
w();
w("| item | status | severity | owner | waiting on |");
w("| --- | --- | --- | --- | --- |");
for (const i of open.sort(bySeverityThenStatus)) w(row(i));
w();
w(`## Closed — ${closed.length}`);
w();
w("`answered` owes nothing further. `fixed` owes a test, and names it here.");
w();
w("| item | status | stays closed because |");
w("| --- | --- | --- |");
for (const i of closed.sort(bySeverityThenStatus)) w(closedRow(i));
w();
w("---");
w();
w("`make issues` · `make issues ID=<id>` · `pnpm gate:issues` · the `issues` skill drives triage.");
w();

writeFileSync(DOC_PATH, out.join("\n"));
console.log(`docs/issues.md — ${open.length} open, ${closed.length} closed`);
