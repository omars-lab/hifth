#!/usr/bin/env node
/**
 * Renderer: packages/etl/scripts/**\/*.mjs → docs/design/etl-scripts.md.
 *
 * This is the census that docs/design/etl-pipeline.md §⑤ used to draw by hand
 * and got wrong — it named about fourteen scripts of thirty-odd, drew four
 * probes of twelve, and missed a whole family. The prose and the flow diagrams
 * in that document stay hand-written, because their edges and their reasons are
 * not in any register; only the list of scripts is derivable, so only the list
 * is generated, and etl-pipeline.md now points here for it.
 *
 * The ground truth is the filesystem, not docs/map.json — enumerating the
 * directory cannot miss a file the way a hand-maintained register can. The map
 * is read only for the one-line blurb of what each script is for; a script the
 * map does not name renders as exactly that, so the gap stays visible.
 *
 * Generated and committed; gate-etl-scripts.mjs fails when the committed copy
 * was built from a different source. Do not hand-edit it.
 *
 * Usage:  node scripts/build-etl-scripts.mjs   (or: make etl-scripts-doc)
 */
import { writeFileSync } from "node:fs";
import { DOC_PATH, GROUPS, payload, etlScriptsHash } from "./etl-scripts.mjs";

const p = payload();
const rowsByGroup = new Map(GROUPS.map(([k]) => [k, []]));
for (const r of p.rows) rowsByGroup.get(r.group).push(r);

const out = [];
const w = (s = "") => out.push(s);
const name = (path) => path.slice("packages/etl/scripts/".length);

w("<!-- generated by scripts/build-etl-scripts.mjs — do not edit; run `make etl-scripts-doc` -->");
w(`<!-- etl-scripts-hash: ${etlScriptsHash()} -->`);
w();
w("# Which scripts build the app's data, and what does each do?");
w();
w("Every runnable script under the pipeline, listed straight off the filesystem and grouped by");
w("what it is for. This page exists because [`etl-pipeline.md`](./etl-pipeline.md) used to keep");
w("this list by hand and it drifted — it named a third of the scripts and missed an entire");
w("family — so the list is now generated and that document points here for it. What is *not*");
w("generated, and stays in `etl-pipeline.md`, is the part a filesystem cannot know: how the data");
w("flows from the printed page to the shards, and why each step is shaped the way it is.");
w();
w("Nothing here is authored. Each script's one-line description is read out of the code map");
w("([`../map.json`](../map.json)); a script the map does not yet name is marked so, which is the");
w("honest state and a small invitation to name it. Change a script or its map note, then run");
w("`make etl-scripts-doc`.");
w();
w(`**${p.total} scripts**, ${p.documented} described in the code map, ${p.total - p.documented} not yet.`);
w();

for (const [key, heading] of GROUPS) {
  const rows = rowsByGroup.get(key);
  if (!rows.length) continue;
  w(`## ${heading} — ${rows.length}`);
  w();
  for (const r of rows.sort((a, b) => a.path.localeCompare(b.path))) {
    const blurb = r.blurb ?? "_not in the code map_";
    w(`- \`${name(r.path)}\` — ${blurb}`);
  }
  w();
}

writeFileSync(DOC_PATH, out.join("\n") + "\n");
console.error(`wrote ${DOC_PATH} — ${p.total} scripts, hash ${etlScriptsHash()}`);
