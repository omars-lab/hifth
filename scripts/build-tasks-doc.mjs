#!/usr/bin/env node
/**
 * Renderer: every register → docs/backlog.md, every open item in full, cut by
 * whose turn it is.
 *
 * The page has to stand on its own. When a working session is cleared, the
 * repository is the only thing left that remembers what is open, so a reader
 * must be able to pick up any item from this page alone: its full text, the
 * notes we kept on it, and where it lives. It opens with a short table of
 * everything, then the items in full.
 *
 * The text is copied in, not written here. Each item is owned by the page it is
 * written on (a design page's open questions, the speed notes, the roadmap's
 * follow-ups, the checks ledger, the decisions index) and read out of it at build
 * time, links rewritten so they still work from here. Edit an item where it
 * lives, then `make tasks-doc`; gate-tasks.mjs refuses a copy that has fallen
 * behind its sources.
 *
 * The order is the argument: what is waiting on a person first, because nobody
 * else can move it; the build's own roadmap last, because it moves slowest.
 *
 * Usage:  node scripts/build-tasks-doc.mjs
 */
import { writeFileSync } from "node:fs";
import { readIssues, linker } from "./issues.mjs";
import { readLedger } from "./validation-ledger.mjs";
import { DOC_PATH, payload, tasksHash } from "./tasks.mjs";

const p = payload();
const ledgerById = new Map((readLedger().checks ?? []).map((c) => [c.id, c]));
const link = linker(ledgerById);
const byId = new Map(readIssues().map((i) => [i.id, i]));

const cell = (s) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const n = (c, one, many) => `${c} ${c === 1 ? one : many}`;

const out = [];
const w = (s = "") => out.push(s);

const order = ["confirmed", "suspected", "open", "blocked"];
const worstFirst = (a, b) =>
  order.indexOf(a.status) - order.indexOf(b.status) || a.id.localeCompare(b.id);
const mine = p.issues.filter((i) => i.owner === "user").sort(worstFirst);
const theirs = p.issues.filter((i) => i.owner !== "user").sort(worstFirst);
const titled = (i) => link(byId.get(i.id) ?? i);

w("<!-- generated by scripts/build-tasks-doc.mjs — do not edit; run `make tasks-doc` -->");
w(`<!-- tasks-hash: ${tasksHash()} -->`);
w();
w("# Backlog — everything still open");
w();
w("Every piece of work and every question this project has written down as unfinished, in full, on");
w("one page. It is the page to open at the start of a session: nothing else needs to be remembered,");
w("and nothing here needs another page to make sense.");
w();
w("Each item is written on the page it belongs to and copied in here when the page is rebuilt, so");
w("**change an item where it lives** (the link under each one), then run `make tasks-doc`. A new");
w("item goes on its owning page and gets a row in [`issues.json`](issues.json); the `issues` skill");
w("walks it. A commit is refused while this page is behind its sources.");
w();
w(
  `**Open now:** ${n(p.decisions.length, "decision", "decisions")} · ` +
    `${n(p.checks.length, "check", "checks")} only a person can do · ` +
    `${mine.length} more waiting on you · ${theirs.length} waiting on whoever picks them up · ` +
    `${n(p.loops.length, "roadmap loop", "roadmap loops")} unfinished.`,
);
w();

// ── The short version ────────────────────────────────────────────────────────
w("## What is open, in one table?");
w();
w("| item | whose turn | status |");
w("| --- | --- | --- |");
for (const d of p.decisions) w(`| [${cell(d.question)}](#${d.id}) | a decision | open |`);
for (const c of p.checks) w(`| [${cell(c.title)}](#check-${c.id}) | a person, by hand | pending |`);
for (const i of mine) w(`| [${cell(titled(i)[0])}](#${i.id}) | you | ${i.status} |`);
for (const i of theirs) w(`| [${cell(titled(i)[0])}](#${i.id}) | whoever picks it up | ${i.status} |`);
w();
w("**The words.** `confirmed` — reproduced, with numbers. `suspected` — read from the code, never");
w("reproduced. `open` — undecided, nothing blocking it. `blocked` — the next step is known and not");
w("available yet. `pending` — a check nobody has run yet.");
w();

// ── Decisions ────────────────────────────────────────────────────────────────
w(`## What is waiting on a decision? — ${p.decisions.length}`);
w();
if (p.decisions.length === 0) {
  w("Nothing. Every question this project has opened has an answer on record.");
  w();
}
for (const d of p.decisions) {
  w(`<a id="${d.id}"></a>`);
  w();
  w(`### ${d.question}`);
  w();
  for (const o of d.options) w(`- **${o.id}** — ${o.label}`);
  w();
  const where = [];
  if (d.page) where.push(`[the options page](${d.page.replace(/^docs\//, "")})`);
  if (d.doc) where.push(`[the record](${d.doc.replace(/^docs\//, "")})`);
  if (where.length) w(`Read ${where.join(" and ")} before choosing. The \`decide\` skill records the answer.`);
  w();
}

// ── Human-only checks ────────────────────────────────────────────────────────
w(`## What can only a person check? — ${p.checks.length}`);
w();
w("A machine can prove the app is well-formed and fast. It cannot judge whether a hop is *true*,");
w("whether a screen reader sounds right, or whether a page still opens after eight days offline.");
w("Each check below says why it matters and what doing it involves; `make validate CHECK=<name>`");
w("prints the full step-by-step with what you should see, and `make record` saves the result.");
w();
for (const c of p.checks) {
  w(`<a id="check-${c.id}"></a>`);
  w();
  w(`### ${c.title}`);
  w();
  const meta = [`run it with \`make validate CHECK=${c.id}\``];
  if (c.blocks.length) meta.push(`it releases ${c.blocks.join(", ")}`);
  w(`*${meta.join(" · ")}*`);
  w();
  if (c.why) {
    w(c.why);
    w();
  }
  if (c.needs.length) {
    w("**You need:**");
    w();
    for (const x of c.needs) w(`- ${x}`);
    w();
  }
  if (c.steps.length) {
    w("**The steps, short:**");
    w();
    c.steps.forEach((s, k) => w(`${k + 1}. ${s}`));
    w();
  }
}

// ── Issues, split by owner ───────────────────────────────────────────────────
const item = (i) => {
  const [title, href] = titled(i);
  w(`<a id="${i.id}"></a>`);
  w();
  w(`### ${title}`);
  w();
  const meta = [`**${i.status}**`, i.severity];
  if (i.blockedBy.length) meta.push(`waiting on ${i.blockedBy.join(", ")}`);
  meta.push(`lives in [${href.split("#")[0]}](${href})`);
  w(meta.join(" · "));
  w();
  if (i.text) {
    w(i.text);
    w();
  }
  if (i.note) {
    w("<details><summary>Our notes on it</summary>");
    w();
    w(i.note);
    w();
    w("</details>");
    w();
  }
};

w(`## What else is waiting on you? — ${mine.length}`);
w();
w("Items only the person who owns this project can settle: a judgement about how the app should");
w("feel, a licence somebody has to read, a device somebody has to hold.");
w();
for (const i of mine) item(i);

w(`## What is waiting on whoever picks it up next? — ${theirs.length}`);
w();
w("Items that need reading, measuring, building or writing rather than a judgement call.");
w();
for (const i of theirs) item(i);

// ── The roadmap ──────────────────────────────────────────────────────────────
w(`## Where is the build up to? — ${n(p.loops.length, "loop", "loops")} not finished`);
w();
w("Read out of the roadmap's status table in [`PLAN.md`](PLAN.md#status--tracking). A loop marked");
w("complete drops off; one that shipped with something still owed stays, because the thing owed is");
w("what this page is for.");
w();
w("| loop | where it stands | what would finish it |");
w("| --- | --- | --- |");
for (const l of p.loops) w(`| ${cell(l.loop)} | ${cell(l.status)} | ${cell(l.exit)} |`);
w();

// ── Where it all lives ───────────────────────────────────────────────────────
w("## Where is each item written?");
w();
w("| kind of item | written in | driver |");
w("| --- | --- | --- |");
w("| a question a design page has not settled | that page's \"Open questions, and what would answer each\" | the `issues` skill |");
w("| speed and size work | [`performance.md`](performance.md) | the `optimizing-performance` skill |");
w("| a roadmap follow-up | [`PLAN.md`](PLAN.md#open-follow-ups) | edited at the end of every loop |");
w("| a check only a person can do | [`validation/ledger.json`](validation/ledger.json) | `make validate` |");
w("| a decision to make | [`decisions.json`](decisions.json) | the `decide` skill |");
w("| the index of all of them | [`issues.json`](issues.json) · [`issues.md`](issues.md) (worst first) | `make issues` |");
w();
w("---");
w();
w("`make tasks` prints the counts in a terminal · `make tasks-doc` rebuilds this page ·");
w("`pnpm gate:tasks` refuses a copy that has fallen behind.");
w();

writeFileSync(DOC_PATH, out.join("\n"));
console.log(
  `docs/backlog.md — ${p.decisions.length} decisions, ${p.checks.length} checks, ` +
    `${mine.length} yours, ${theirs.length} open, ${p.loops.length} loops`,
);
