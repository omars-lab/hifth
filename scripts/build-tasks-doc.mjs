#!/usr/bin/env node
/**
 * Renderer: the four registers → docs/tasks.md, cut by whose turn it is.
 *
 * Markdown, and for the same reason issues.md is: this is read on GitHub by
 * somebody deciding what to pick up, not on a phone in a masjid basement.
 *
 * Every title and every link is read out of the register that owns the item at
 * build time. Nothing on this page is authored here, which is the discipline
 * the whole repo is built on: the moment a title lives in two files, one of
 * them is a copy that is right for a while and then quietly stops being right,
 * and a stale index reads exactly like a fresh one.
 *
 * The order of the sections is the argument. What is waiting on a person comes
 * first, because those are the items that cannot be picked up by anybody else
 * and therefore the ones a reader is uniquely able to move. The build's own
 * roadmap comes last, because it is the slowest-moving thing here.
 *
 * Generated and committed; gate-tasks.mjs fails when the committed copy was
 * built from a different source. Do not hand-edit it.
 *
 * Usage:  node scripts/build-tasks-doc.mjs
 */
import { writeFileSync } from "node:fs";
import { readIssues, linker } from "./issues.mjs";
import { readLedger } from "./validation-ledger.mjs";
import { DOC_PATH, payload, tasksHash } from "./tasks.mjs";

const p = payload();
const ledgerById = new Map((readLedger().checks ?? []).map((c) => [c.id, c]));
const link = linker(ledgerById);
const byId = new Map(readIssues().map((i) => [i.id, i]));

const cell = (s) => (s ?? "").replace(/\|/g, "\\|");
const n = (c, one, many) => `${c} ${c === 1 ? one : many}`;

const out = [];
const w = (s = "") => out.push(s);

w("<!-- generated by scripts/build-tasks-doc.mjs — do not edit; run `make tasks-doc` -->");
w(`<!-- tasks-hash: ${tasksHash()} -->`);
w();
w("# What is still open?");
w();
w("Everything this repository has written down as unfinished, ordered by **whose turn it is**.");
w("[`issues.md`](issues.md) holds the same items ordered worst-first, which is the page to read");
w("when you are deciding what to fix; this is the page to read when you have an hour and want to");
w("know what only you can move.");
w();
w("Nothing here is authored. Every title is read out of the document that owns the item, and every");
w("link goes there. Change an item where it lives, then run `make tasks-doc`.");
w();

// ── Decisions ────────────────────────────────────────────────────────────────
w(`## What is waiting on a decision? — ${p.decisions.length}`);
w();
w("Questions this project has opened and not closed. Each one has a page you can open in a browser,");
w("with every option drawn on a real page of the mus'haf at the size it would actually be used —");
w("a wash you cannot see at that size is an answer, and it is one no paragraph would have given you.");
w("Nothing downstream of these moves until they are settled.");
w();
w("| question | options | read it | it is written up in |");
w("| --- | --- | --- | --- |");
for (const d of p.decisions) {
  const page = d.page ? `[the page](${d.page.replace(/^docs\//, "")})` : "—";
  const live = d.artifact ? ` · [in a browser](${d.artifact})` : "";
  const doc = d.doc ? `[${cell(d.doc.replace(/^docs\//, ""))}](${d.doc.replace(/^docs\//, "")})` : "—";
  w(`| ${cell(d.question)} | ${d.options} | ${page}${live} | ${doc} |`);
}
w();
w("`make decisions` lists them · the `decide` skill walks one from question to record.");
w();

// ── Human-only checks ────────────────────────────────────────────────────────
w(`## What can only a person check? — ${p.checks.length}`);
w();
w("A machine can prove this app is well-formed, fast and legible. It cannot judge whether a hop is");
w("*true*, whether a screen reader sounds like something you would say, or whether a page still");
w("opens after eight days in a bag. These are the ones that need a human, and each carries its own");
w("runbook — what you need, what to run, and what you should expect to see.");
w();
w("| check | it releases | run it with |");
w("| --- | --- | --- |");
for (const c of p.checks) {
  const blocks = c.blocks.length ? c.blocks.join(", ") : "—";
  w(`| ${cell(c.title)} | ${cell(blocks)} | \`make validate CHECK=${c.id}\` |`);
}
w();
w("`make validate` lists them · `make guide` renders them for a phone · `make record` banks a result.");
w();

// ── Issues, split by owner ───────────────────────────────────────────────────
const row = (i) => {
  const src = byId.get(i.id) ?? i;
  const [title, href] = link(src);
  const wait = i.blockedBy.join(", ");
  return `| [${cell(title)}](${href}) | ${i.status} | ${i.severity} | ${cell(wait) || "—"} |`;
};
const head = () => {
  w("| item | status | severity | waiting on |");
  w("| --- | --- | --- | --- |");
};
const order = ["confirmed", "suspected", "open", "blocked"];
const worstFirst = (a, b) =>
  order.indexOf(a.status) - order.indexOf(b.status) || a.id.localeCompare(b.id);

const mine = p.issues.filter((i) => i.owner === "user").sort(worstFirst);
const theirs = p.issues.filter((i) => i.owner !== "user").sort(worstFirst);

w(`## What else is waiting on you? — ${mine.length}`);
w();
w("Open items nobody but the person who owns this project can settle — a judgement about how the");
w("app should feel, a licence somebody has to read, a device somebody has to hold. The checks above");
w("are not repeated here.");
w();
head();
for (const i of mine) w(row(i));
w();

w(`## What is waiting on whoever picks it up next? — ${theirs.length}`);
w();
w("Open items that need reading, measuring or writing rather than deciding. `confirmed` means it was");
w("reproduced with numbers in its source; `suspected` means it was read from the code and never");
w("reproduced; `blocked` means the next step is named and unavailable.");
w();
head();
for (const i of theirs) w(row(i));
w();

// ── The roadmap ──────────────────────────────────────────────────────────────
w(`## Where is the build up to? — ${n(p.loops.length, "loop", "loops")} not finished`);
w();
w("The roadmap of record is [`PLAN.md`](PLAN.md#status--tracking) and this is read out of it. A loop");
w("marked complete is gone from this table; one that shipped with something owed is not, because the");
w("thing owed is exactly what this page is for.");
w();
w("| loop | where it stands | what would finish it |");
w("| --- | --- | --- |");
for (const l of p.loops) w(`| ${cell(l.loop)} | ${cell(l.status)} | ${cell(l.exit)} |`);
w();

// ── Where it all lives ───────────────────────────────────────────────────────
w("## Where each of these actually lives");
w();
w("Every register is hand-edited and this page is generated from all of them. Change an item where");
w("it lives; never here.");
w();
w("| register | question it answers | driver |");
w("| --- | --- | --- |");
w("| [`decisions.json`](decisions.json) | what did we decide, and why? | `make decisions` · the `decide` skill |");
w("| [`validation/ledger.json`](validation/ledger.json) | what can only a human check? | `make validate` |");
w("| [`issues.json`](issues.json) | what is still open, worst first? | `make issues` · the `issues` skill |");
w("| [`PLAN.md`](PLAN.md#status--tracking) | where is the build up to? | edited at the end of every loop |");
w("| [`map.json`](map.json) | where does this feature live? | `make map` · the `extend` skill |");
w("| [`use-cases.json`](use-cases.json) | who uses this, and what proves it? | `make use-cases` |");
w();
w("---");
w();
w("`make tasks` prints this in a terminal · `make tasks-doc` re-renders this page · `pnpm gate:tasks`");
w("refuses a copy built from a source that has since moved.");
w();

writeFileSync(DOC_PATH, out.join("\n"));
console.log(
  `docs/tasks.md — ${p.decisions.length} decisions, ${p.checks.length} checks, ` +
    `${mine.length} yours, ${theirs.length} open, ${p.loops.length} loops`,
);
