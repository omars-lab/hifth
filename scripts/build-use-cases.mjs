#!/usr/bin/env node
/**
 * Renderer: docs/use-cases.json → docs/use-cases.md.
 *
 * Markdown rather than HTML, unlike the validation guide, and for the opposite
 * reason. The guide is read on a phone in a masjid basement, so it is a
 * self-contained page served over the LAN. This is read on GitHub, in a pull
 * request, by someone deciding whether a change breaks a promise — so it wants
 * to be the thing the code host renders by itself, with a mermaid diagram it
 * draws natively and a table you can scan.
 *
 * The diagram is the point. A table of twenty-eight use cases is a list; the
 * same twenty-eight arranged by actor, with the <<include>> arrows drawn, is
 * the shape of the product — you can see at a glance that everything the hafiz
 * does hangs off one gesture, and that CI is an actor with promises of its own.
 *
 * Mermaid has no UML use-case diagram, so this uses `flowchart` with the UML
 * conventions transplanted: actors are square, use cases are ovals (`( )` in
 * mermaid is exactly the UML oval), one subgraph per actor, and <<include>> is
 * a dotted arrow. Close enough to read as a use-case diagram to anyone who has
 * seen one, and it renders on GitHub with no toolchain at all.
 *
 * The file is generated and committed, and gate-use-cases.mjs fails when the
 * committed copy was built from a different source — the same rule the ETL
 * output and the validation guide live under. Do not hand-edit it.
 *
 * Usage:  node scripts/build-use-cases.mjs
 */
import { writeFileSync } from "node:fs";
import { locate, locateTest } from "./code-pointers.mjs";
import { readUseCases, useCasesHash, DOC_PATH, isGateProof } from "./use-cases.mjs";

const data = readUseCases();
const { actors, useCases } = data;

/**
 * Mermaid node ids have to be identifier-ish, and labels have to survive being
 * quoted. Ids are derived rather than stored so the JSON never has to know it
 * is being drawn.
 */
const nodeId = (id) => "uc_" + id.replace(/-/g, "_");
const actorId = (id) => "ac_" + id.replace(/-/g, "_");

/**
 * Mermaid takes `"…"` labels but chokes on a `"` inside one, and renders `#`
 * as an entity escape. Both appear in ordinary English goals, so both are
 * neutralised here rather than banned in the source.
 */
const label = (s) => s.replace(/"/g, "'").replace(/#/g, "＃");

/** Wrap a long goal onto two or three lines so a node stays readable. */
function wrapLabel(s, width = 34) {
  const words = s.split(" ");
  const lines = [""];
  for (const w of words) {
    if ((lines.at(-1) + " " + w).trim().length > width) lines.push(w);
    else lines[lines.length - 1] = (lines.at(-1) + " " + w).trim();
  }
  return lines.join("<br/>");
}

function mermaid() {
  const out = ["flowchart LR"];
  for (const a of actors) {
    const mine = useCases.filter((u) => u.actor === a.id);
    out.push(`  subgraph ${actorId(a.id)}_g["${label(a.name)}"]`);
    out.push(`    direction TB`);
    for (const u of mine) {
      out.push(`    ${nodeId(u.id)}("${label(wrapLabel(u.goal))}")`);
    }
    out.push(`  end`);
  }
  // <<include>> arrows, drawn after every node exists so mermaid never has to
  // infer a node's home subgraph from the edge that first mentions it — which
  // is how a use case ends up drawn under the wrong actor.
  for (const u of useCases) {
    for (const inc of u.includes ?? []) {
      out.push(`  ${nodeId(u.id)} -.->|needs| ${nodeId(inc)}`);
    }
  }
  out.push(`  classDef uc fill:#fbf8f2,stroke:#1f6f66,stroke-width:1px,color:#26201a;`);
  out.push(`  class ${useCases.map((u) => nodeId(u.id)).join(",")} uc;`);
  return out.join("\n");
}

/** `file:line`, computed now, never stored. Broken pointers are shown, not hidden. */
function codeLink(c) {
  const at = locate(c.file, c.symbol);
  return at.ok ? `[\`${c.file}:${at.line}\`](../${c.file}#L${at.line}) — \`${c.symbol}\`` : `\`${c.file}\` ⚠ ${at.why}`;
}

function proofLink(p) {
  if (isGateProof(p)) return `\`pnpm ${p.gate}\``;
  const at = locateTest(p.file, p.test);
  return at.ok
    ? `[\`${p.file}:${at.line}\`](../${p.file}#L${at.line}) — “${p.test}”`
    : `\`${p.file}\` ⚠ ${at.why}`;
}

function body() {
  const lines = [];
  lines.push(`<!-- use-cases-hash: ${useCasesHash(data)} -->`);
  lines.push(`<!-- GENERATED by scripts/build-use-cases.mjs from docs/use-cases.json.`);
  lines.push(`     Edit the JSON, then run \`make use-cases-doc\`. Hand edits are lost`);
  lines.push(`     and gate:use-cases fails when this file and the source disagree. -->`);
  lines.push(``);
  lines.push(`# Who uses Hifth, and what proves it works`);
  lines.push(``);
  lines.push(
    `Every promise this app makes, whose promise it is, where it happens in the code, and the test or gate that would fail if we broke it. Generated from [\`docs/use-cases.json\`](use-cases.json) — see that file's \`$comment\` for why each field exists.`,
  );
  lines.push(``);
  lines.push(
    `Sister documents: [\`docs/map.json\`](map.json) answers *where do I change this* (\`make map\`), and [\`docs/validation/ledger.json\`](validation/ledger.json) tracks the checks a machine cannot do (\`make validate\`).`,
  );
  lines.push(``);
  lines.push("```mermaid");
  lines.push(mermaid());
  lines.push("```");
  lines.push(``);

  for (const a of actors) {
    const mine = useCases.filter((u) => u.actor === a.id);
    lines.push(`## ${a.name}`);
    lines.push(``);
    lines.push(a.what);
    lines.push(``);
    for (const u of mine) {
      lines.push(`### ${u.goal}`);
      lines.push(``);
      lines.push(
        `\`${u.id}\` · change it with \`make map FEATURE=${u.feature}\`` +
          (u.includes?.length ? ` · needs first: ${u.includes.map((i) => `\`${i}\``).join(", ")}` : ""),
      );
      lines.push(``);
      lines.push(`| | |`);
      lines.push(`|---|---|`);
      for (const c of u.code ?? []) lines.push(`| happens in | ${codeLink(c)} |`);
      for (const p of u.proof ?? []) lines.push(`| proven by | ${proofLink(p)} |`);
      lines.push(``);
      if (u.gap) {
        lines.push(`> **Not proven:** ${u.gap}`);
        lines.push(``);
      }
    }
  }

  const gaps = useCases.filter((u) => u.gap);
  lines.push(`## What is promised more than it is proven`);
  lines.push(``);
  lines.push(
    `${gaps.length} of ${useCases.length} use cases carry a \`gap\` — a promise whose proof is thinner than the promise. They are collected here because a hole listed once beside its own use case is a hole nobody counts.`,
  );
  lines.push(``);
  for (const u of gaps) lines.push(`- **${u.goal}** — ${u.gap}`);
  lines.push(``);
  return lines.join("\n");
}

writeFileSync(DOC_PATH, body() + "\n", "utf8");
console.log(
  `  use-cases → docs/use-cases.md  (${actors.length} actors, ${useCases.length} use cases, ${useCasesHash(data)})`,
);
