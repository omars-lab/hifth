#!/usr/bin/env node
/**
 * Find the verses that are the same verse, twice.
 *
 * The app's look-alike set was built from *recurring phrases* — short sequences
 * that turn up in many places. Held up against an outside library used only as a
 * ruler (`probe-qul-rulers.mjs`), that set turned out to miss almost all of a
 * different kind of look-alike: whole verses repeated word for word in two
 * places. Those are the hardest of all for a memoriser — a verse repeated whole,
 * pages apart, with only its surroundings to tell the two apart — and the bridge
 * the app exists to build was the one it was not building here.
 *
 * This closes that gap **from our own bytes**, not the ruler's. The verified
 * Arabic the morphology corpus carries (`data/roots/…`, already vendored, its
 * provenance recorded there) is read at build time; two verses are twins when
 * their words, reduced to the rasm skeleton the app already compares on
 * (`wordsByAyah` → `normalise` in morphology.mjs), are identical in sequence.
 * Nothing of the ruler is used to find them, and nothing but verse *numbers* is
 * written out — no Qur'an text leaves this script.
 *
 * ## Why a word floor, and why four
 *
 * Two verses of one or two words match by coincidence, not confusion: the
 * disconnected-letter openings (الم, حم) and the shortest refrains are identical
 * but a reader never mixes them up. The ruler's own "strong" line falls at four
 * words, and measured here the counts agree almost exactly — floor 4 yields 636
 * pairs where the ruler's whole-verse set has 635 — so four is where this cuts.
 * A four-word refrain that *is* a genuine confusion (ar-Raḥmān's «فبأي آلاء ربكما
 * تكذبان», thirty-one times) sits right at the floor and is kept.
 *
 *     pnpm --filter @hifth/etl build:twins
 *
 * Output: data/mutashabihat/verbatim-twins.json — clusters of verse keys, each
 * cluster a set of verses identical to one another. `build-adjacency.mjs` reads
 * it and joins every pair in a cluster with a `twin` mutashabih edge; the
 * existing span machinery then washes the whole verse, because every word is
 * shared. The count re-derives by rerunning this script.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toAbsoluteAyah } from "@hifth/core";
import { wordsByAyah } from "./morphology.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "data", "mutashabihat", "verbatim-twins.json");

/** Verses this short match by coincidence, not confusion (see header). */
const FLOOR_WORDS = 4;

const abs = (key) => {
  const [s, a] = key.split(":").map(Number);
  return toAbsoluteAyah(s, a);
};

// Group every verse by its exact rasm-skeleton word sequence — the same
// per-word normalisation the shipped edge builder compares on.
const groups = new Map();
for (const [key, words] of wordsByAyah()) {
  if (words.length < FLOOR_WORDS) continue;
  const sig = words.join(">");
  if (!groups.has(sig)) groups.set(sig, []);
  groups.get(sig).push(key);
}

// A cluster is a set of two or more verses identical to one another. Keys within
// a cluster and clusters among themselves are sorted by mus'haf order, so the
// output is byte-stable across runs.
const clusters = [...groups.values()]
  .filter((keys) => keys.length >= 2)
  .map((keys) => keys.sort((x, y) => abs(x) - abs(y)))
  .sort((p, q) => abs(p[0]) - abs(q[0]));

const pairs = clusters.reduce((t, c) => t + (c.length * (c.length - 1)) / 2, 0);
const verses = clusters.reduce((t, c) => t + c.length, 0);

const out = {
  $comment:
    "GENERATED by build-verbatim-twins.mjs — do not hand-edit. Clusters of " +
    "verse keys whose words are identical in rasm-skeleton sequence, derived at " +
    "build time from the vendored Quranic Arabic Corpus morphology " +
    "(data/roots/, GPL, provenance recorded there). Verse numbers only; no " +
    "Qur'an text. Rebuild: pnpm --filter @hifth/etl build:twins.",
  floorWords: FLOOR_WORDS,
  clusters: clusters.length,
  pairs,
  verses,
  twins: clusters,
};

writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${OUT.replace(HERE, ".")}  ${clusters.length} clusters, ` +
    `${pairs} pairs, ${verses} verses (floor ${FLOOR_WORDS} words)`,
);
